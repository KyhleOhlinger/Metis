/** Planner domain types, constants, and factory helpers. */

export type DayName = "Monday" | "Tuesday" | "Wednesday" | "Thursday" | "Friday";
export type TaskStatus = "work" | "holiday" | "sick" | "pto" | "personal" | "offsite";
export type PlannerTab = "daily" | "weekly" | "monthly" | "templates" | "tracker" | "goals" | "reviews";
export type TemplateCadence = "daily" | "weekly" | "monthly" | "interval";
export type TrackerStatus = "Complete" | "Coming Up" | "Pending";

export type DayEntry = {
  status: TaskStatus;
  planned?: string;
  did?: string;
  label?: string;
  plannedAutoGenerated?: boolean;
  plannedTemplateIds?: string[];
  trackerSourceType?: "holiday" | "pto" | "conference" | "trip";
  trackerSourceId?: string;
  officeTripBanner?: string;
  officeTripEventId?: string;
};

export type WeekEntry = Partial<Record<DayName, DayEntry>>;
export type WeeklyReviewEntry = { content: string };
export type MonthlyReviewEntry = { content: string; achievements?: string; date_completed?: string };
export type MonthEntry = {
  daily_logs: Record<string, WeekEntry>;
  weekly_reviews: Record<string, WeeklyReviewEntry>;
  monthly_review: MonthlyReviewEntry;
};
export type YearEntry = Record<string, MonthEntry>;
export type PublicHolidayEntry = {
  id: string;
  name: string;
  date: string;
  status: TrackerStatus;
  notes: string;
};
export type PtoEntry = {
  id: string;
  description: string;
  startDate: string;
  endDate: string;
  daysTotal: number;
  daysTaken: number;
  status: TrackerStatus;
  notes: string;
};
export type ConferenceEntry = {
  id: string;
  eventName: string;
  startDate: string;
  endDate: string;
  location: string;
  activity: "Booked" | "Pending";
  status: TrackerStatus;
  notes: string;
};
export type OfficeTripEntry = {
  id: string;
  tripName: string;
  startDate: string;
  endDate: string;
  location: string;
  activity: "Booked" | "Pending";
  status: TrackerStatus;
  notes: string;
};
export type TrackerData = {
  public_holidays: PublicHolidayEntry[];
  pto: PtoEntry[];
  conferences: ConferenceEntry[];
  office_trips: OfficeTripEntry[];
  pto_stats: {
    total_allocation: number;
  };
};
export type TaskManifest = {
  tracker?: TrackerData;
  [year: string]: YearEntry | TrackerData | undefined;
};
export type PlanTemplate = {
  id: string;
  name: string;
  cadence: TemplateCadence;
  intervalDays: number;
  startDate: string;
  content: string;
  enabled: boolean;
  recurrenceDay: DayName;
};
export type PlannerLayoutTemplates = {
  dailyPrimaryLabel: string;
  dailySecondaryEnabled: boolean;
  dailySecondaryLabel: string;
  weeklyLeftHeader: string;
  weeklyRightHeader: string;
  weeklyDefaultContent: string;
  monthlyLeftHeader: string;
  monthlyRightHeader: string;
  monthlyPrompts: string[];
};

export type GoalSection = {
  id: string;
  title: string;
  content: string;
};

export type ReviewTableRow = {
  id: string;
  cycleLabel: string;
  managerStrengths: string;
  managerOpportunity: string;
  personalStrengths: string;
  personalOpportunity: string;
};

export type ReviewsTableState = {
  headers: [string, string, string, string, string];
  rows: ReviewTableRow[];
};

