export function makeRowId(): string {
  return `${Date.now()}-${Math.random().toString(36).slice(2)}`;
}

export function makeMonthlyTemplateContent(prompts: string[] = MONTHLY_PROMPTS): string {
  return prompts.map((prompt) => `- ${prompt}\n`).join("\n");
}

export function makeEmptyMonthEntry(): MonthEntry {
  return {
    daily_logs: {},
    weekly_reviews: {},
    monthly_review: { content: "", achievements: "" },
  };
}

export function makeEmptyTracker(): TrackerData {
  return {
    public_holidays: [],
    pto: [],
    conferences: [],
    office_trips: [],
    pto_stats: { total_allocation: 26 },
  };
}
